/**
 * Spintax Parser and Variable Personalization with Fallbacks
 */

export function parseSpintax(text: string): string {
  if (!text) return '';

  const spintaxRegex = /\{([^{}|]+\|[^{}]+)\}/;
  let matches;
  let parsed = text;

  let iterations = 0;
  while ((matches = spintaxRegex.exec(parsed)) !== null && iterations < 150) {
    const options = matches[1].split('|');
    const choice = options[Math.floor(Math.random() * options.length)];
    parsed = parsed.replace(matches[0], choice);
    iterations++;
  }

  return parsed;
}

/**
 * Calculates total unique combinations that can be generated by spintax
 */
export function countSpintaxVariations(text: string): number {
  if (!text) return 1;

  const spintaxRegex = /\{([^{}|]+\|[^{}]+)\}/g;
  let count = 1;
  let match;

  while ((match = spintaxRegex.exec(text)) !== null) {
    const options = match[1].split('|');
    if (options.length > 1) {
      count *= options.length;
    }
  }

  return Math.min(count, 1000000);
}

/**
 * Replaces variables with support for fallback syntax:
 * {name|there} -> uses "there" if name is empty or null
 * {company|your company}
 */
export function substituteVariables(text: string, variables: Record<string, any> = {}): string {
  if (!text) return '';

  return text.replace(/\{([a-zA-Z0-9_-]+)(?:\|([^{}]+))?\}/g, (match, key, fallback) => {
    // If it looks like Spintax with pipe on both sides, don't substitute
    if (match.includes('|') && !key.match(/^[a-zA-Z0-9_-]+$/)) {
      return match;
    }

    const lowerKey = key.toLowerCase();
    for (const [varName, varVal] of Object.entries(variables)) {
      if (varName.toLowerCase() === lowerKey) {
        if (varVal !== undefined && varVal !== null && String(varVal).trim() !== '') {
          return String(varVal);
        }
      }
    }

    return fallback !== undefined ? fallback : match;
  });
}

/**
 * Complete message renderer:
 * 1. Substitutes variables with fallback
 * 2. Resolves Spintax options
 * 3. Appends optional opt-out footer
 */
export function renderMessage(
  template: string,
  recipient: { name?: string | null; phone?: string; custom_variables?: any } = {},
  options: { appendOptOut?: boolean; optOutText?: string } = {}
): string {
  const vars: Record<string, any> = {
    name: recipient.name || '',
    phone: recipient.phone || '',
    ...(typeof recipient.custom_variables === 'string'
      ? JSON.parse(recipient.custom_variables || '{}')
      : recipient.custom_variables || {}),
  };

  let rendered = substituteVariables(template, vars);
  rendered = parseSpintax(rendered);

  if (options.appendOptOut) {
    const footer = options.optOutText || 'Reply STOP to unsubscribe';
    rendered += `\n\n_${footer}_`;
  }

  return rendered;
}

/**
 * Converts WhatsApp formatting into HTML:
 * *bold* -> <strong>
 * _italic_ -> <em>
 * ~strike~ -> <del>
 * ```mono``` -> <code>
 */
export function formatWhatsAppToHtml(rawText: string): string {
  if (!rawText) return '';

  let escaped = rawText
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

  // Triple backticks (monospace code blocks)
  escaped = escaped.replace(/```([\s\S]*?)```/g, '<code class="bg-emerald-950/40 text-emerald-300 font-mono text-xs px-1.5 py-0.5 rounded block whitespace-pre-wrap my-1">$1</code>');

  // Single backticks
  escaped = escaped.replace(/`([^`\n]+)`/g, '<code class="bg-emerald-950/40 text-emerald-300 font-mono text-xs px-1 py-0.5 rounded">$1</code>');

  // Bold: *text*
  escaped = escaped.replace(/(?<!\w)\*([^*\n]+)\*(?!\w)/g, '<strong>$1</strong>');

  // Italic: _text_
  escaped = escaped.replace(/(?<!\w)_([^_\n]+)_(?!\w)/g, '<em>$1</em>');

  // Strike: ~text~
  escaped = escaped.replace(/(?<!\w)~([^~\n]+)~(?!\w)/g, '<del class="line-through">$1</del>');

  // Line breaks
  escaped = escaped.replace(/\n/g, '<br/>');

  return escaped;
}

